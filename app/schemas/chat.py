"""Pydantic schemas for Chat Completions, Streaming, Tools, and Structured Outputs."""

import time
from typing import Any

from pydantic import BaseModel, Field


class FunctionCall(BaseModel):
    """Function call data returned by the model."""

    name: str
    arguments: str


class ToolCall(BaseModel):
    """Tool invocation payload."""

    id: str
    type: str = "function"
    function: FunctionCall


class ChatMessage(BaseModel):
    """Single chat message within a conversational sequence."""

    role: str = Field(..., description="Role: system, user, assistant, tool")
    content: str | None = Field(default=None, description="Text content of the message")
    name: str | None = Field(default=None, description="Optional author name")
    tool_calls: list[ToolCall] | None = Field(
        default=None, description="Optional tool calls generated by assistant"
    )
    tool_call_id: str | None = Field(
        default=None, description="ID of tool call this message responds to"
    )


class ChatCompletionRequest(BaseModel):
    """Request payload for /v1/chat/completions and /v1/chat/stream."""

    messages: list[ChatMessage] = Field(..., min_length=1, description="Message history")
    model: str | None = Field(
        default=None, description="Target model (defaults to config DEFAULT_MODEL)"
    )
    temperature: float | None = Field(default=0.7, ge=0.0, le=2.0)
    top_p: float | None = Field(default=1.0, ge=0.0, le=1.0)
    max_tokens: int | None = Field(default=1024, ge=1, le=131072)
    stream: bool = Field(default=False, description="Enable SSE token streaming")
    use_cache: bool = Field(default=True, description="Enable semantic caching lookup")
    tools: list[dict[str, Any]] | None = Field(
        default=None, description="List of available tools for function calling"
    )
    tool_choice: str | dict[str, Any] | None = Field(
        default=None, description="Tool selection policy: none, auto, required, or specific tool"
    )
    response_format: dict[str, Any] | None = Field(
        default=None, description="Structured Output JSON schema enforcement"
    )


class ChatUsage(BaseModel):
    """Token consumption statistics."""

    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0


class ChatCompletionChoice(BaseModel):
    """Individual completion output."""

    index: int = 0
    message: ChatMessage
    finish_reason: str | None = "stop"


class ChatCompletionResponse(BaseModel):
    """Complete response structure for chat completion."""

    id: str = Field(default_factory=lambda: f"chatcmpl-{int(time.time()*1000)}")
    object: str = "chat.completion"
    created: int = Field(default_factory=lambda: int(time.time()))
    model: str
    choices: list[ChatCompletionChoice]
    usage: ChatUsage | None = None
    cached: bool = False
    ttft_ms: float | None = None
    latency_ms: float | None = None
